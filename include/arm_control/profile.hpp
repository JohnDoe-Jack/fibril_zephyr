// **この機体の値。書き換えるのはここだけ。**
//
// 実機を測って変わるのは肘角の許容範囲と原点オフセットで、どちらもここにある。
// 位置指定の集約初期化を使っていないので、フィールドが増えても既存の行はずれない。
// 角度は **度**で書く — 実機で測るときの単位と揃えるため。
//
// 置いてよいもの: この機体そのものの寸法・比・向き・限界、運転の上限。
// 置いてはいけないもの: 設置環境の制約 (作業台の縁や柱)。あれは作業領域の話で、
// 同じ機体を別の場所へ持っていけば変わる。main.cpp が組み立てる。

#include "arm/kinematics.hpp"
#include "arm/motion.hpp"
#include "arm/transmission.hpp"

namespace armctl {

// ============================================================================
// 機構
// ============================================================================

// **実測値 (2026-09-18 に部品を作り直して変わった。以前は 500 / 630)。**
// 肩の回転軸から肘の回転軸まで、肘の回転軸からハンド中心まで。
//
// **ここを変えたら下の肘角の下限とモータ速度の上限も見直す。** 3 つは
// 3v/(l1 sin e) で結びついていて、リンクが短いほど必要なモータ速度が上がる。
inline constexpr float link1_mm = 480.0f;  // 上腕 (肩 → 肘)
inline constexpr float link2_mm = 580.0f;  // 前腕 (肘 → ハンド中心)

// 肘角 |e| の許容範囲。**実測 (2026-09-11) から決めた。**
//
// 機構の実際: 伸ばし切りで **0 度**、畳み切りで **150 度** (干渉で止まる)。
// ソフトの限界はその内側に取る。理由が両側で違う。
//
// **畳み側 145 度 — 突き当てないため。** 機構は 150 度で止まるので、そこへ
// 指令を出し続けると位置ループが電流上限まで押し込んで失速する。5 度の余裕。
//
// **伸ばし側 20 度 — 死点とモータ速度の両方から。** 0 度は死点で、
// sin(e) が 0 に近づくとヤコビアンが退化し、手先の速度に対して必要な関節速度が
// 発散する。肩は減速比 3 なので、必要なモータ速度は 3v/(l1 sin e)。
//
//   手先 225 mm/s のとき  e=10 度 → 8.10 rad/s   e=20 度 → 4.11 rad/s
//
// **10 度だとモータ速度上限 (4.5 rad/s) を超えていた。** 境界付近で
// モータが先に頭打ちになり、指令だけが先に進んで実機が遅れる状態だった。
// 20 度なら収まり、**失う外側の到達距離は 1056 → 1044 mm の 12 mm だけ**。
//
// **速度を上げるならこの下限も一緒に見直すこと。** 両者は 3v/(l1 sin e) で
// 結びついている。
//
// 到達円環: 20 度 → 外 1044 mm / 145 度 → 内 333 mm (2026-09-18 のリンク長)。
// リンク長が違うので、畳み切っても |l1 − l2| = 100 mm 残る。
inline constexpr float elbow_min_deg = 20.0f;
inline constexpr float elbow_max_deg = 145.0f;

// 組み立てで肘の曲がる向きが片側に固定される。
inline constexpr arm::kin::ElbowSide elbow_side = arm::kin::ElbowSide::Positive;

// 特異点判定の閾値 (無次元、|sin e| と比べる)。肘角の範囲を守っていれば
// |sin e| >= sin(10 度) = 0.17 なので、これは範囲外から呼ばれたときの保険。
inline constexpr float singularity_eps = 1.0e-3f;

// ============================================================================
// 伝達比
// ============================================================================

// **向きは実機で決めた (2026-09-11)。** 机上の推論だけでは足りなかった。
//
// 当初は「肩は外部平歯車 1 段だから反転して -1、肘は直結だから +1」としていたが、
// 実機では **2 軸とも逆に回った**。歯車 1 段が反転するという推論は正しく、
// 足りなかったのは**モータの正回転の向き**のほう — 想定と逆だった。
// 資料に記述が無いので、机上では決めようがなかった値になる。
//
//   肩 = 歯車の反転 × モータの反転 = 同相 → +1
//   肘 = モータの反転だけ                → -1
//
// **キー割り当てで直してはいけない。** 手触りは直るが座標系が鏡のままになり、
// 作業領域のガードが反対側の半平面を守ることになる (site の y は片側だけ)。
inline constexpr float  shoulder_ratio     = 3.0f;
inline constexpr int8_t shoulder_direction = +1;

// 肘: 平行リンクのため直結 (減速比 1)。向きは上と同じ理由で -1。
inline constexpr float  elbow_ratio     = 1.0f;
inline constexpr int8_t elbow_direction = -1;

// 原点オフセット [rad]。モータ角 0 に対応する関節角。
//
// **効くのは原点合わせの前の表示にだけ。** ここの値は「まだ合わせていないとき」の
// 仮で、エンコーダの原点とアームの 0 度が一致している前提。実機では一致しない。
//
// **書き写しても原点合わせは省けない。** 原点合わせ済みかどうかは実行時の状態で、
// それが立つのは操作者が基準姿勢で宣言したときだけ。肩は減速比 3 で、モータの
// 電源投入後の角度は 0〜2π で返るため、書き写した値には 120° 単位の曖昧さが残る。
inline constexpr float shoulder_offset_rad = 0.0f;
inline constexpr float elbow_offset_rad    = 0.0f;

// 原点合わせの基準姿勢 [deg]。**実機に印を付けておく姿勢。**
// ここへ手で持っていって `h` を押すと、そこが下の角度だとして逆算する。
//
// **肩 -90 度から戻した (ユーザ指定 2026-09-13)。** 一度は据え付けの都合で
// 上腕を -y へ向けたが、その姿勢だと運転中に肩が RS00 の可動角 (仕様表
// -4pi..+4pi) の端へ届いて指令が切り詰められ、異常停止した。
//
// **窓の位置はここで決まる。** calibrateHome() が
// `offset = home_theta1_deg - raw` を入れるので、基準姿勢を選ぶことは
// 「モータの可動角のどこを使うか」を選ぶことでもある。窓の幅は肩で
// 関節 480 度 (減速比 3 で ±4pi / 3) あり、1 周より広いので到達できる点は
// 減らないが、**よく使う領域が窓の中央に来る姿勢を選ぶ**必要がある。
inline constexpr float home_theta1_deg = 0.0f;   // 上腕を +x 方向へ
inline constexpr float home_theta2_deg = 90.0f;  // 前腕を +y 方向へ (肘角 90 度)

// ============================================================================
// アクチュエータ
// ============================================================================

inline constexpr uint8_t shoulder_can_id = 1;
inline constexpr uint8_t elbow_can_id    = 2;

// 位置モードへ入れるときの上限。
//
// **手先の速度を上げるならここも上げる。** これはモータ軸の速度上限で、
// 手先 1 mm/s に要る関節速度は姿勢で変わる (ヤコビアンの逆)。肘角が小さい
// (伸びきりに近い) ほど必要な関節速度が跳ね上がるので、手先側だけ上げると
// 境界付近でモータが先に頭打ちになり、**指令だけが先に進んで実機が遅れる**。
// 遅れたぶんはキーを離した瞬間に追いつくので、動きが引っかかる。
//
// **必要な値は肘角の下限から出る。** 肩は減速比 3 なので 3v/(l1 sin e)。
// 手先 450 mm/s・肘角の下限 20 度で **8.22 rad/s** なので 8.5 とした
// (2026-09-18。上腕が 500 → 480 mm に短くなり、必要な速度が 7.89 → 8.22 に上がった。
// 以前の 8.0 のままだと伸びきり付近で足りず、**指令だけが先に進んで実機が遅れる** —
// 手先の速度を変えていなくても、リンクを短くすると起きる)。
// RS00 の 0x7017 limit_spd の定義域は 0..33 rad/s。
//
// **これは速度の頭打ちであって力の上限ではない。** 上げても人へ加わる力は増えない
// (力を決めるのは下の電流上限)。
//
// **電流上限は据え置き、ただし要観察。** 6.0 A は RS00 のトルク定数
// (14 N*m / 16 A) で約 5.25 N*m にあたる。実測では通常運転 2 N*m、
// 手で止めたとき 5 N*m だったので、**手で抵抗すると既に天井に近い**。
// 加速度を 2 倍にしたぶん動的なトルクが増えるので、追従が鈍るようなら
// ここを上げることになる — ただし**人へ加わりうる力が上がる**トレードオフ。
inline constexpr float joint_speed_limit_rad_s = 8.5f;
inline constexpr float joint_current_limit_a   = 6.0f;

// 指令が途絶えたときモータが自分で脱力するまでの時間 [ms]。
// **制御基板が死んだときの最後の砦。** 0 にすると無効。
//
// **ms で書く。** モータ側のレジスタは独自の tick 単位だが、その換算を知るのは
// アクチュエータのアダプタ (robstride_joint.cpp) の仕事で、機体の値を書くこの
// ファイルがモータの型を知る必要はない。
inline constexpr uint32_t can_timeout_ms = 100u;

// 過トルクで脱力する閾値 [N*m]。**0 以下なら無効。**
//
// **実測から決めた (2026-09-11)。** 挟み込みを検出して保持をやめるための値で、
// 上下を実測が挟んでいる。
//
//   通常運転の最大        1.4 N*m  (速度 450 / 加速度 1200 で一通り動かした)
//   手で止めたときの実測  5   N*m
//   電流上限の天井        5.25 N*m (6.0 A × 14 N*m / 16 A)
//
// **5.0 はユーザ指定 (2026-09-11)。** 通常運転の 3.6 倍、手で止めたときの実測と
// 同じ高さで、電流上限が作る天井 5.25 N*m のすぐ下。
//
// **この高さの意味を書いておく。** 天井が 5.25 なので、5.0 に達するのは
// モータがほぼ出せるかぎり押しているときだけ。**誤トリップはまず起きない
// 代わりに、挟まれてから解放されるまでに掛かる力は大きい。**
// 下げるほど早く解放されるが、通常運転 (1.4) に近づくほど誤トリップが増える。
//
// **天井より下であることがこの値の必須条件。** 超えるとトルクが届かず、
// 保護が一度も効かない。電流上限を下げるときは一緒に見直すこと
// (tests/test_arm_profile.cpp がこの関係を検査している)。
//
// **速度や加速度を変えたら測り直す。** 通常運転のトルクが動く。
// 報告に出している「トルク最大」がその材料になる。
inline constexpr float over_torque_nm = 5.0f;

// ============================================================================
// 制御周期
// ============================================================================

// **ここに置くのは、周期が他の値と噛み合っていなければならないから。**
// main.cpp の無名 namespace に閉じていたころは、can_timeout が制御周期の何倍
// あるかをゲートから見られなかった。「運転の上限」と同じ性質の値なのでここへ置く。
inline constexpr uint32_t control_hz        = 500;
inline constexpr uint32_t control_period_us = 1000000u / control_hz;
inline constexpr float    control_dt        = 1.0f / static_cast<float>(control_hz);

// ============================================================================
// 運転の上限 (機体の性能ではなく運用の判断)
// ============================================================================

// **速度も加速度も 2 倍にした (2026-09-11、ユーザ指定)。**
//
// 1 度速度だけを 1.5 倍にしたが「まだ遅い」という評価だった。**遅く感じるのは
// 最高速ではなく加速度のほう** — ジョグ 90 mm/s・300 mm/s^2 では最高速に達する
// までに 0.30 秒・13.5 mm かかり、**短く叩く操作は一度も最高速へ届かない**。
// 速度だけ上げてもそこは変わらない。
//
// **躍度も一緒に上げる。** 躍度を据え置くと加速度が上限へ達するまでの時間が
// 倍になり (600/6000 = 0.10 秒 → 1200/6000 = 0.20 秒)、「加速度 2 倍」が
// 実際の動きに出ない。a/jerk を保つように 12000 へ。
inline constexpr float move_v_max    = 450.0f;    // mm/s
inline constexpr float move_a_max    = 1200.0f;   // mm/s^2
inline constexpr float move_jerk     = 12000.0f;  // mm/s^3。0 以下なら台形

inline constexpr float jog_v_max = 180.0f;  // mm/s   手先ジョグ
inline constexpr float jog_a_max = 600.0f;  // mm/s^2

inline constexpr float joint_jog_v_max = 0.90f;  // rad/s  関節ジョグ
inline constexpr float joint_jog_a_max = 3.00f;  // rad/s^2

// ============================================================================
// 組み立て
// ============================================================================

constexpr arm::kin::Config kinematicsConfig() {
    arm::kin::Config c{};
    c.l1         = link1_mm;
    c.l2         = link2_mm;
    c.elbow_side = elbow_side;
    c.elbow_min  = elbow_min_deg * arm::DEG;
    c.elbow_max  = elbow_max_deg * arm::DEG;
    c.det_eps    = singularity_eps;
    return c;
}

constexpr arm::tx::Config transmissionConfig() {
    arm::tx::Config c{};
    c.shoulder.ratio     = shoulder_ratio;
    c.shoulder.direction = shoulder_direction;
    c.shoulder.offset    = shoulder_offset_rad;
    c.elbow.ratio        = elbow_ratio;
    c.elbow.direction    = elbow_direction;
    c.elbow.offset       = elbow_offset_rad;
    return c;
}

constexpr arm::motion::TrapezoidProfile moveProfile() {
    arm::motion::TrapezoidProfile p{};
    p.v_max = move_v_max;
    p.a_max = move_a_max;
    p.jerk  = move_jerk;
    return p;
}

}  // namespace armctl

