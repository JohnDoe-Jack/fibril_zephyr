#pragma once
// アームが 1 つの関節に要求すること。**アクチュエータの口ではなく、アプリの口。**
//
// ============================================================================
// なぜ lib/ ではなくここに置くか
// ============================================================================
//
// 要求を持っているのはアーム側なので、口を定義するのもアーム側。これは依存の
// 向きの話で、再利用の話ではない。`lib/robstride/` に「共通アクチュエータ基底」を
// 置くとアクチュエータ各社に共通の語彙を押し付けることになり、それは元仕様 §5 が
// 禁じたもの — トルクと電流とパルス幅を 1 つの動詞にまとめようとすると必ず壊れる。
//
// ここで固定しているのは 1 種類の要求だけ:
//
//   **rad で絶対位置を受け取り、rad で返し、脱力できる回転関節**
//
// この語彙なら RobStride でも RoboMaster でも RC サーボでも意味が変わらない。
// `release()` は RobStride の disable()、RC サーボの detach() に対応する —
// どちらも「トルクを出さない状態にする」で、docs/decisions.md の語彙と揃っている。
//
// ============================================================================
// 実行コンテキスト
// ============================================================================
//
//   main のみ (待ちを含んでよい): init / enterPositionMode
//   割り込みから呼んでよい (待たない): commandPosition / readPosition / readTorque /
//                                     release / isAlive
//
// 速度・電流・トルクの上限は**実装が構築時に持つ**。アクチュエータごとに単位も
// 意味も違うので、この口には載せない。

#include <cstdint>

#include "arm/arm_types.hpp"

namespace armctl {

// アクチュエータ固有の設定を書いたあと、**読み返して確かめた結果。**
//
// 設定そのもの (通信途絶保護など) はアクチュエータごとに違うので JointDrive の
// 口には載らない。だが「書けたと言えるか」の語彙は共通で、**送信バッファに
// 積めたことと、本当にその値になったことは違う**という区別はどのモータでも要る。
//
// 数値を明示するのは、ログに出た値の意味が並べ替えで変わらないため。
enum class VerifyResult : uint8_t {
    Verified = 0,  // 応答が来て、書いた値と一致した
    // 読み要求を送信バッファに積めなかった。**詰まっているだけかもしれない** —
    // 積み直してよいのはこの値だけ。書けたかどうかは、まだ何も分かっていない。
    NotSent = 1,
    NoReply = 2,  // 要求は積めたが、期限内に応答が来ない
    // 応答は来たが、書いた値と違う。**積み直しても同じ答えが返る。**
    Mismatch = 3,
};

class JointDrive {
public:
    virtual ~JointDrive() = default;

    JointDrive(const JointDrive&)            = delete;
    JointDrive& operator=(const JointDrive&) = delete;

    // バスなどへ登録する。**main のみ。**
    virtual bool init() = 0;

    // 絶対位置で追従するモードへ入れる。**main のみ (待ちを含む)。**
    virtual bool enterPositionMode() = 0;

    // 目標位置 [rad]。**多回転を畳まないこと。** 割り込みから呼んでよい。
    //
    // 返すのは「**指令どおりに**受け取ったか」であって、フレームが出たかではない。
    // アクチュエータが自分の仕様範囲へ丸めたなら false — 丸めを true にすると、
    // 上位は指令どおり動いていると信じたまま、実際には別の姿勢へ向かう。
    // 2 軸のうち片方だけが頭打ちになる形でそれが起きると、機構が壊れる。
    virtual bool commandPosition(float rad) = 0;

    // 直近に受け取った位置 [rad]。一度も受け取っていなければ false。
    virtual bool readPosition(float& out) const = 0;

    // 脱力。**失敗しうる** (バスが死んでいれば送れない) ので戻り値を見ること。
    virtual bool release() = 0;

    // 応答が途絶えていないか。
    virtual bool isAlive() const = 0;

    // **本当にトルクを出せる状態か。** `isAlive()` とは別の問い。
    //
    // アクチュエータが自分で保護動作に入って脱力しても、通信には応答し続ける
    // ことがある。そのとき `isAlive()` も `commandPosition()` も真のままなので、
    // 制御ループは指令を送り続け、腕は動かないのに画面上は追従して見える。
    // 分からないときは false — 「たぶん通電している」で動かさない。
    virtual bool isEnergized() const = 0;

    // 直近に受け取った出力トルク [N*m]。一度も受け取っていなければ false。
    //
    // **符号は向きを持つ。** 判定に使うのは大きさ (絶対値) のほうで、
    // どちらへ押されているかは人が見るための情報。
    // 位置と同じく「受け取った値」であって、いま出ているトルクの実測ではない。
    virtual bool readTorque(float& out) const = 0;

    // アクチュエータ側にラッチした故障を解除する。**復帰の 1 本目。**
    // これを送らないと、使能し直しても同じ故障で落ちる。
    virtual bool clearFaults() = 0;

protected:
    JointDrive() = default;
};

}  // namespace armctl

